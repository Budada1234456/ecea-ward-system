import { execFileSync, spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { basename, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = fileURLToPath(new URL(".", import.meta.url));
const REPOSITORY_ROOT = resolve(SCRIPT_DIR, "..");
const DEFAULT_OUTPUT = resolve(
  REPOSITORY_ROOT,
  "src",
  "data",
  "disciplines.js",
);
const EXPECTED_SHA256 =
  "E6FE7693A8F199F304E91157A5BD5B0BDAF914EBDA275F1A36F7F7FAA8403E53";
const EXPECTED_COUNTS = Object.freeze({ 3: 62, 5: 738, 7: 2732 });
const EXPECTED_GROUP_COUNTS = Object.freeze({ 5: 61, 7: 373 });
const PARENT_OVERRIDES = Object.freeze({
  1903510: "19030",
  1903520: "19030",
  1903530: "19030",
  1903540: "19030",
  1903599: "19030",
});

function fail(message) {
  throw new Error(`Discipline extraction failed: ${message}`);
}

function findPdfToText() {
  const candidates = [
    process.env.XPDF_PDFTOTEXT,
    "pdftotext",
    "C:\\Program Files\\Git\\mingw64\\bin\\pdftotext.exe",
  ].filter(Boolean);

  for (const candidate of candidates) {
    const probe = spawnSync(candidate, ["-v"], { stdio: "ignore" });
    if (!probe.error) return candidate;
  }
  fail(
    "Xpdf pdftotext was not found; set XPDF_PDFTOTEXT to its executable path",
  );
}

function extractTableText(pdfPath) {
  return execFileSync(
    findPdfToText(),
    ["-f", "8", "-l", "91", "-table", "-enc", "UTF-8", pdfPath, "-"],
    { encoding: "utf8", maxBuffer: 16 * 1024 * 1024 },
  );
}

function parseRows(tableText) {
  const rows = [];
  const codePattern = /^(\d{3}(?:\d{2}){0,2})\s{2,}(\S.*)$/u;

  for (const [index, line] of tableText.split(/\r?\n/u).entries()) {
    const match = line.match(codePattern);
    if (!match) continue;

    const [, code, columns] = match;
    const name = columns.split(/\s{2,}/u, 1)[0].replace(/\s+/gu, "");
    if (!name) fail(`empty name at extracted line ${index + 1}`);
    rows.push([code, name]);
  }
  return rows;
}

function expectedParent(code) {
  return PARENT_OVERRIDES[code] ?? code.slice(0, -2);
}

function validateRows(rows) {
  const byCode = new Map();
  const counts = { 3: 0, 5: 0, 7: 0 };
  const groupCounts = { 5: 0, 7: 0 };

  for (const [code, name] of rows) {
    if (byCode.has(code)) fail(`duplicate code ${code}`);
    byCode.set(code, name);
    counts[code.length] += 1;
    if (code.length > 3 && code.endsWith("99")) groupCounts[code.length] += 1;
  }

  for (const length of [3, 5, 7]) {
    if (counts[length] !== EXPECTED_COUNTS[length]) {
      fail(
        `expected ${EXPECTED_COUNTS[length]} ${length}-digit rows, got ${counts[length]}`,
      );
    }
  }
  for (const length of [5, 7]) {
    if (groupCounts[length] !== EXPECTED_GROUP_COUNTS[length]) {
      fail(
        `expected ${EXPECTED_GROUP_COUNTS[length]} ${length}-digit group rows, got ${groupCounts[length]}`,
      );
    }
  }

  for (const [code] of rows) {
    if (code.length > 3 && !byCode.has(expectedParent(code))) {
      fail(`missing parent ${expectedParent(code)} for ${code}`);
    }
  }

  const representativeRows = {
    110: "数学",
    1101410: "演绎逻辑学",
    18067: "人类学",
    1806799: "人类学其他学科",
    19030: "发展心理学",
    1903510: "婴儿心理学",
    480: "能源科学技术",
    91099: "统计学其他学科",
  };
  for (const [code, expectedName] of Object.entries(representativeRows)) {
    if (byCode.get(code) !== expectedName) {
      fail(
        `expected ${code} to be ${expectedName}, got ${byCode.get(code) ?? "<missing>"}`,
      );
    }
  }
}

function serializeRows(rows) {
  return rows
    .map(([code, name]) => `  ${JSON.stringify([code, name])},`)
    .join("\n");
}

function createModule(rows, sourceFilename) {
  return `/**
 * Complete GB/T 13745-2009 Table 1 discipline classification.
 *
 * Generated by scripts/generate-disciplines.mjs. Do not edit records manually.
 */
export const DISCIPLINE_DATASET_META = Object.freeze({
  standard: "GB/T 13745-2009",
  title: "学科分类与代码",
  sourceStatus: "verified-table-extraction",
  sourceDocument: ${JSON.stringify(sourceFilename)},
  sourceSha256: "${EXPECTED_SHA256}",
  sourcePdfPages: Object.freeze([8, 91]),
  extractionTool: "Xpdf pdftotext -table",
  extractionDate: "2026-09-15",
  reviewStatus: "automated-validation-and-representative-visual-review",
  expectedCodeLengths: Object.freeze([3, 5, 7]),
  recordCount: 3532,
  tableCodeRowCounts: Object.freeze({ level1: 62, level2: 738, level3: 2732 }),
  clause52DeclaredCounts: Object.freeze({ level1: 62, level2: 676, level3: 2382 }),
  groupCodeCounts: Object.freeze({ level2: 61, level3: 373 }),
  countPolicy:
    "Includes every code-bearing row in Table 1; excludes uncoded cross-references in the name column.",
  countNote:
    "Clause 5.2 declares 62/676/2382 entries, while direct enumeration of Table 1 yields 62/738/2732 code-bearing rows. No rows were dropped to force the declared counts.",
  hierarchyNote:
    "Table 1 prints 19030 for 发展心理学 and 19035xx for its children; those children are explicitly attached to 19030 without changing the published codes.",
  validationVersion: 2,
});

const PARENT_CODE_OVERRIDES = Object.freeze({
  "1903510": "19030",
  "1903520": "19030",
  "1903530": "19030",
  "1903540": "19030",
  "1903599": "19030",
});

const DISCIPLINE_ROWS = Object.freeze([
${serializeRows(rows)}
]);

function expectedParentCode(code) {
  return PARENT_CODE_OVERRIDES[code] ?? code.slice(0, -2);
}

function expectedPathForCode(code) {
  if (code.length === 3) return [code];
  const parentCode = expectedParentCode(code);
  return [...expectedPathForCode(parentCode), code];
}

export const disciplines = Object.freeze(
  DISCIPLINE_ROWS.map(([code, name]) => {
    const level = code.length === 3 ? 1 : code.length === 5 ? 2 : 3;
    const parentCode = level === 1 ? null : expectedParentCode(code);
    return Object.freeze({
      code,
      name,
      level,
      parentCode,
      path: Object.freeze(expectedPathForCode(code)),
    });
  }),
);

export function validateDisciplineRecords(records = disciplines) {
  const errors = [];
  const byCode = new Map();
  if (!Array.isArray(records)) {
    return { valid: false, errors: ["records must be an array"] };
  }

  for (const item of records) {
    if (!item || typeof item !== "object") {
      errors.push("record must be an object");
      continue;
    }
    const code = String(item.code || "");
    const name = String(item.name || "").trim();
    if (!/^\\d{3}(\\d{2})?(\\d{2})?$/.test(code)) {
      errors.push(\`invalid code: \${code || "<empty>"}\`);
    }
    if (!name) errors.push(\`empty name for code: \${code || "<empty>"}\`);
    if (byCode.has(code)) errors.push(\`duplicate code: \${code}\`);
    byCode.set(code, item);

    if (!/^\\d{3}(\\d{2})?(\\d{2})?$/.test(code)) continue;

    const expectedLevel = code.length === 3 ? 1 : code.length === 5 ? 2 : 3;
    if (item.level !== expectedLevel) {
      errors.push(\`invalid level for \${code}: expected \${expectedLevel}\`);
    }
    if (expectedLevel === 1 && item.parentCode != null) {
      errors.push(\`top-level record \${code} cannot have a parent\`);
    }
    const expectedPath = expectedPathForCode(code);
    if (
      !Array.isArray(item.path) ||
      item.path.length !== expectedPath.length ||
      item.path.some((pathCode, index) => pathCode !== expectedPath[index])
    ) {
      errors.push(\`invalid path for \${code}: expected \${expectedPath.join(" > ")}\`);
    }
  }

  for (const [code, item] of byCode) {
    if (!/^\\d{5}(\\d{2})?$/.test(code)) continue;
    const parentCode = String(item.parentCode || "");
    const expectedParent = expectedParentCode(code);
    if (parentCode !== expectedParent) {
      errors.push(\`invalid parent for \${code}: \${parentCode || "<empty>"}\`);
    }
    if (!byCode.has(expectedParent)) {
      errors.push(\`missing parent for \${code}: \${expectedParent}\`);
    }
  }

  return { valid: errors.length === 0, errors };
}

export default disciplines;
`;
}

if (!process.argv[2]) {
  fail(
    "source PDF path is required; run npm run generate:disciplines -- /path/to/13745-2009-gbt-cd-300.pdf",
  );
}
const sourcePath = resolve(process.argv[2]);
const outputPath = resolve(process.argv[3] || DEFAULT_OUTPUT);
if (!existsSync(sourcePath)) fail(`source PDF not found: ${sourcePath}`);

const source = readFileSync(sourcePath);
const actualSha256 = createHash("sha256")
  .update(source)
  .digest("hex")
  .toUpperCase();
if (actualSha256 !== EXPECTED_SHA256) {
  fail(`source SHA-256 is ${actualSha256}, expected ${EXPECTED_SHA256}`);
}

const rows = parseRows(extractTableText(sourcePath));
validateRows(rows);
writeFileSync(outputPath, createModule(rows, basename(sourcePath)), "utf8");
console.log(`Generated ${rows.length} discipline records in ${outputPath}`);
